#!/bin/sh
# ======================================================================
#  使用守护 · 管理后台  —— 启动脚本
#
#  用法：sh start.sh
#
#  等价于 `sh run.sh start`，单独放一份是为了让"启动/停止"这两个动作
#  看起来对称，不用记参数。已经在跑的话会先停再起（不会出现两个进程抢端口）。
# ======================================================================

set -eu
APP_DIR=$(cd "$(dirname "$0")" && pwd)
exec sh "$APP_DIR/run.sh" start
